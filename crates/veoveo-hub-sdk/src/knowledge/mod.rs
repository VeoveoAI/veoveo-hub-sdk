//! The knowledge contract, the MCP extension `ai.veoveo/knowledge`: how a server whose
//! records people search lets every client search them the same way. Each server
//! searches only its own records, under its own read rule; a client that wants several
//! servers calls each one's search.
//!
//! - A resource template whose records can be searched carries
//!   `_meta["ai.veoveo/knowledge"]`, a [`CollectionMarker`] naming its
//!   [`KnowledgeCollection`], `{slug}.{plural}`, such as `artifact.artifacts` for
//!   `artifact://artifacts/{artifact_id}`.
//! - The server serves one tool, [`TOOL`], `search_knowledge`, which callers see as
//!   `{slug}__search_knowledge`. Its input is a [`KnowledgeQuery`] of ordered
//!   [`ContentPart`]s, text or media a caller signed, [`SignedMedia`]; its output is
//!   [`KnowledgeResults`], hits in rank order, with one `resource_link` per hit in the
//!   result content. A caller reads a hit through its server for the record itself.
//! - Every collection lives in one multimodal embedding space, so a server answers a
//!   query in any modality and declares none.
//!
//! These types are the contract feature's, with schemas generated by Schemars, so a
//! server in another language implements the same contract against the same schemas.
//! A Rust server implements `KnowledgeSearch` in the `server` feature, which also holds
//! the checks every result passes before it leaves the server, and embeds through an
//! `Embedder`, in the `client` feature.
