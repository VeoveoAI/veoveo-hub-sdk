/// The extension a server declares in `server/discover` exactly when it searches a
/// marked collection, and the `_meta` key of each template's [`CollectionMarker`].
pub const EXTENSION_ID: &str = "ai.veoveo/knowledge";
/// The search tool's name on its server; callers see `{slug}__search_knowledge`.
pub const TOOL: &str = "search_knowledge";
/// The most hits one search returns.
pub const MAX_HITS: u32 = 20;
/// The hits a query asks for when it names no limit.
pub const DEFAULT_LIMIT: u32 = 10;
/// The most characters, Unicode scalar values, a hit's snippet holds.
pub const MAX_SNIPPET_CHARS: usize = 320;
/// The most collections a query names.
pub const MAX_QUERY_COLLECTIONS: usize = 16;

/// How many hits a query asks for: 1 to [`MAX_HITS`].
pub type KnowledgeLimit = PageSize<MAX_HITS>;

/// A searchable collection of one server's records, `{slug}.{plural}`: the server's slug
/// and the plural noun of its records, such as `artifact.artifacts`. The plural starts
/// with a lowercase ASCII letter and continues with lowercase ASCII letters, digits, `-`
/// or `_`; the whole name holds at most 128 bytes.
#[veoveo_types::id(text(KnowledgeCollections))]
pub struct KnowledgeCollection(String);

#[doc(hidden)]
pub struct KnowledgeCollections;
impl veoveo_types::IdProfile for KnowledgeCollections {
    type Error = IdentifierError;
    const PROFILE: veoveo_types::IdProfileSpec<Self::Error> =
        veoveo_types::IdProfileSpec::text(|value, _| validate_collection(value));
}

const MAX_COLLECTION_BYTES: usize = 128;

fn validate_collection(value: &str) -> Result<(), IdentifierError> {
    if value.len() > MAX_COLLECTION_BYTES {
        return Err(IdentifierError::new(value, "must be at most 128 bytes"));
    }
    let Some((slug, plural)) = value.split_once('.') else {
        return Err(IdentifierError::new(
            value,
            "a knowledge collection is {slug}.{plural}",
        ));
    };
    ServerSlug::parse(slug)?;
    let mut bytes = plural.bytes();
    let plural_admitted = bytes.next().is_some_and(|first| first.is_ascii_lowercase())
        && bytes.all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-' || b == b'_');
    if !plural_admitted {
        return Err(IdentifierError::new(
            value,
            "a collection's plural starts with a lowercase ASCII letter and holds lowercase \
             ASCII letters, digits, hyphen or underscore",
        ));
    }
    Ok(())
}

impl KnowledgeCollection {
    /// The collection `{server}.{plural}`.
    pub fn of(server: &ServerSlug, plural: &str) -> Result<Self, IdentifierError> {
        Self::parse(format!("{server}.{plural}"))
    }

    /// The server whose records the collection holds.
    pub fn server(&self) -> ServerSlug {
        ServerSlug::parse(self.server_str()).expect("an admitted collection names a server")
    }

    /// The plural noun of its records.
    pub fn plural(&self) -> &str {
        self.as_str()
            .split_once('.')
            .map_or("", |(_, plural)| plural)
    }

    pub fn is_owned_by(&self, server: &ServerSlug) -> bool {
        self.server_str() == server.as_str()
    }

    fn server_str(&self) -> &str {
        self.as_str()
            .split_once('.')
            .map_or(self.as_str(), |(slug, _)| slug)
    }
}

/// `_meta["ai.veoveo/knowledge"]` of a resource template whose records can be searched:
/// `{"collection": "{slug}.{plural}"}`. The template's own name says what the records
/// are; the marker adds nothing else.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct CollectionMarker {
    pub collection: KnowledgeCollection,
}

impl CollectionMarker {
    /// The marker in a template's `_meta`, when it carries one; an error when the value
    /// under [`EXTENSION_ID`] is not a marker.
    pub fn from_meta(
        meta: &serde_json::Map<String, serde_json::Value>,
    ) -> Option<Result<Self, serde_json::Error>> {
        meta.get(EXTENSION_ID)
            .map(|value| serde_json::from_value(value.clone()))
    }

    /// The marker as the value it takes under [`EXTENSION_ID`].
    pub fn to_value(&self) -> serde_json::Value {
        serde_json::to_value(self).expect("a collection marker serializes")
    }
}

/// The input of `search_knowledge`: 1 to 16 ordered parts in any modality, at most 16 of
/// the server's marked collections to search, each once, all of them when it names none,
/// and how many hits to return, 1 to 20, 10 when it names none.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct KnowledgeQuery {
    /// The query: text, image, audio and video parts in order.
    pub parts: ContentParts,
    /// The marked collections of this server to search, at most 16 and each once; every
    /// one when empty or omitted.
    #[serde(default, skip_serializing_if = "CollectionSelection::is_empty")]
    pub collections: CollectionSelection,
    /// At most this many hits, 1 to 20.
    #[serde(default = "default_limit")]
    pub limit: KnowledgeLimit,
}

fn default_limit() -> KnowledgeLimit {
    KnowledgeLimit::new(DEFAULT_LIMIT).expect("the default limit is within 1 to 20")
}

impl KnowledgeQuery {
    /// A query of `parts` over every marked collection, with the default limit.
    pub fn new(parts: ContentParts) -> Self {
        Self {
            parts,
            collections: CollectionSelection::default(),
            limit: default_limit(),
        }
    }

    /// Whether the query lets `collection` answer: it names none, or names it.
    pub fn searches(&self, collection: &KnowledgeCollection) -> bool {
        self.collections.is_empty() || self.collections.contains(collection)
    }
}

/// The collections a query names: at most [`MAX_QUERY_COLLECTIONS`], each once, in the
/// order named. Empty, it names none, and every marked collection answers.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct CollectionSelection(Vec<KnowledgeCollection>);

impl CollectionSelection {
    pub fn new(collections: Vec<KnowledgeCollection>) -> Result<Self, KnowledgeValueError> {
        if collections.len() > MAX_QUERY_COLLECTIONS {
            return Err(KnowledgeValueError::new(
                "a query names at most 16 collections",
            ));
        }
        for (index, collection) in collections.iter().enumerate() {
            if collections[..index].contains(collection) {
                return Err(KnowledgeValueError::new(
                    "a query names each collection once",
                ));
            }
        }
        Ok(Self(collections))
    }

    /// One collection alone.
    pub fn one(collection: KnowledgeCollection) -> Self {
        Self(vec![collection])
    }

    pub fn is_empty(&self) -> bool {
        self.0.is_empty()
    }

    pub fn contains(&self, collection: &KnowledgeCollection) -> bool {
        self.0.contains(collection)
    }

    pub fn as_slice(&self) -> &[KnowledgeCollection] {
        &self.0
    }

    pub fn iter(&self) -> std::slice::Iter<'_, KnowledgeCollection> {
        self.0.iter()
    }
}

impl<'a> IntoIterator for &'a CollectionSelection {
    type Item = &'a KnowledgeCollection;
    type IntoIter = std::slice::Iter<'a, KnowledgeCollection>;
    fn into_iter(self) -> Self::IntoIter {
        self.iter()
    }
}

impl Serialize for CollectionSelection {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        self.0.serialize(serializer)
    }
}

impl<'de> Deserialize<'de> for CollectionSelection {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        Self::new(Vec::deserialize(deserializer)?).map_err(serde::de::Error::custom)
    }
}

impl JsonSchema for CollectionSelection {
    fn schema_name() -> Cow<'static, str> {
        "CollectionSelection".into()
    }
    fn inline_schema() -> bool {
        true
    }
    fn json_schema(generator: &mut SchemaGenerator) -> Schema {
        let collection = generator.subschema_for::<KnowledgeCollection>();
        json_schema!({
            "type": "array",
            "items": collection,
            "maxItems": MAX_QUERY_COLLECTIONS,
            "uniqueItems": true,
        })
    }
}

/// A hit's excerpt of its record: at most [`MAX_SNIPPET_CHARS`] characters.
/// [`Snippet::new`] trims longer text; a received snippet that is longer is refused.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct Snippet(String);

impl Snippet {
    /// `text`, trimmed to its first 320 characters.
    pub fn new(text: impl Into<String>) -> Self {
        let mut text = text.into();
        if let Some((end, _)) = text.char_indices().nth(MAX_SNIPPET_CHARS) {
            text.truncate(end);
        }
        Self(text)
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl Serialize for Snippet {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_str(&self.0)
    }
}

impl<'de> Deserialize<'de> for Snippet {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let text = String::deserialize(deserializer)?;
        if text.chars().count() > MAX_SNIPPET_CHARS {
            return Err(serde::de::Error::custom(
                "a snippet holds at most 320 characters",
            ));
        }
        Ok(Self(text))
    }
}

impl JsonSchema for Snippet {
    fn schema_name() -> Cow<'static, str> {
        "Snippet".into()
    }
    fn json_schema(_: &mut SchemaGenerator) -> Schema {
        json_schema!({"type": "string", "maxLength": MAX_SNIPPET_CHARS})
    }
}

impl fmt::Display for Snippet {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// One record a search found: its address, which the caller reads through its server,
/// its collection, title and an excerpt, and when the record keeps one, when it last
/// changed.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct KnowledgeHit {
    pub uri: ResourceUri,
    pub collection: KnowledgeCollection,
    pub title: String,
    pub snippet: Snippet,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub modified_at: Option<DateTime<Utc>>,
}

/// The output of `search_knowledge`: at most [`MAX_HITS`] hits in rank order.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(transparent)]
pub struct KnowledgeResults(Checked<ResultsValue>);

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
#[schemars(rename = "KnowledgeResults", inline)]
struct ResultsValue {
    #[schemars(length(max = 20))]
    hits: Vec<KnowledgeHit>,
}

impl Check for ResultsValue {
    type Error = KnowledgeValueError;
    fn check(&self) -> Result<(), Self::Error> {
        if self.hits.len() > MAX_HITS as usize {
            return Err(KnowledgeValueError::new("a search returns at most 20 hits"));
        }
        Ok(())
    }
}

impl KnowledgeResults {
    pub fn new(hits: Vec<KnowledgeHit>) -> Result<Self, KnowledgeValueError> {
        Checked::new(ResultsValue { hits }).map(Self)
    }

    /// The hits in rank order.
    pub fn hits(&self) -> &[KnowledgeHit] {
        &self.0.hits
    }

    pub fn into_hits(self) -> Vec<KnowledgeHit> {
        self.0.into_inner().hits
    }
}

